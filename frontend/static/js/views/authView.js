import { $, showBanner, fieldErr, esc } from '../utils/dom.js';

const FORMS = { login: '#loginForm', register: '#registerForm', forgot: '#forgotForm', reset: '#resetForm',
  totpsetup: '#totpSetupForm', totpverify: '#totpVerifyForm' };
const FOCUS = { login: '#liEmail', register: '#rgName', forgot: '#fgEmail', reset: '#rsCode', totpsetup: '#tsCode', totpverify: '#tvCode' };

export const authView = {
  setMode(mode) {
    Object.entries(FORMS).forEach(([m, sel]) => { $(sel).hidden = m !== mode; });
    $('#authSeg').hidden = mode !== 'login' && mode !== 'register';
    $('#tabLogin').setAttribute('aria-selected', mode === 'login');
    $('#tabRegister').setAttribute('aria-selected', mode === 'register');
    ['#loginErr', '#loginOk', '#regErr', '#fgErr', '#rsErr', '#tsErr', '#tvErr'].forEach(id => showBanner(id));
    if (mode === 'forgot' && !$('#fgEmail').value) $('#fgEmail').value = $('#liEmail').value;
    if (FOCUS[mode]) $(FOCUS[mode]).focus();
  },
  banner: showBanner,
  fieldErr,
  clearFields(ids) { ids.forEach(x => { $(x).value = ''; }); },
  setStrength(barSel, helpSel, inputSel, score) {
    $(barSel).dataset.level = $(inputSel).value ? Math.max(1, score) : 0;
    $(helpSel).textContent = $(inputSel).value
      ? ['', 'Weak password', 'Fair password', 'Good password', 'Strong password'][Math.max(1, score)]
      : 'Use at least 6 characters with letters and numbers.';
  },
  // Shows the QR code only (drawn by the server as SVG). The secret key is never shown as text.
  renderQr(boxSel, setup) {
    const holder = $(boxSel);
    if (setup && setup.qr_svg) holder.innerHTML = setup.qr_svg;       // trusted: generated by our own server
    else holder.textContent = 'The QR code could not be created. Reload the page and try again.';
  },
  // Only used in development, when the server has no SMTP configured and hands back the code.
  showDevMail(email, code) {
    const box = $('#demoMail');
    box.hidden = !code;
    if (code) box.innerHTML = '<b>Development mode.</b> No e-mail server is configured, so the code is shown here instead of being e-mailed.<br>To: ' +
      esc(email) + '<span class="code">' + esc(code) + '</span>';
  }
};
